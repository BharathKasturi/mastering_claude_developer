"""Generate learning_path.yaml for the CCDV-F learning-path app from manifest.json.

The course is flat — 26 notebooks at the content root — so the app cannot group
them by folder. This writes the config that does the grouping: one section per
exam domain, each claiming its notebooks by filename, with `num` pinned so the
app's computed lesson numbers come out as the exam's own skill codes (1.1 … 8.3).

    python3 gen_learning_path.py

Re-run it after adding a lesson to manifest.json. Never hand-edit the yaml.
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent

# Study order, not the published order — see EXAM_GUIDE_OFFICIAL.md in the quiz app.
DOMAINS = {
    1: ("Claude Code", 3.1),
    2: ("Prompt & Context Engineering", 11.0),
    3: ("Model Selection & Optimization", 16.8),
    4: ("Applications & Integration", 33.1),
    5: ("Eval, Testing & Debugging", 2.6),
    6: ("Tools & MCPs", 10.6),
    7: ("Security & Safety", 8.1),
    8: ("Agents & Workflows", 14.7),
}

HEAD = """# Mastering Claude Developer (CCDV-F) — learning path configuration
#
# GENERATED by gen_learning_path.py from manifest.json — re-run it, don't hand-edit.
# The content dir is flat (every notebook at the root), so each section claims
# its notebooks by filename; `num` pins the section number so lesson numbers
# come out as the exam's own skill codes (1.1 … 8.3), not list positions.

title: Mastering Claude Developer (CCDV-F)

sections:
  - dir: d0_setup
    name: "Getting Started"
    num: 0
    order: 5
    modules:
      - file: 00_setup.ipynb
        name: "Shared Setup — API key, client, helpers"
        order: 10
"""


# The Day-1 Claude Code CLI lab. Not exam content, so it is not in manifest.json —
# it is a real folder the scanner already finds; this only names and orders it.
WORKSHOP = """  - dir: workshop
    name: "Claude Code CLI Workshop (Day 1 lab)"
    num: 9
    order: 90
    modules:
      - file: 00_setup_install.ipynb
        name: "Install Claude Code & First Session"
        description: "Install, sign in, first session and slash commands - and the one small project every later lab is built inside."
        order: 10
      - file: 01_project_setup_memory.ipynb
        name: "Project Setup & Memory (features 1-5)"
        order: 20
      - file: 02_session_context.ipynb
        name: "Session & Context (features 10-15)"
        order: 30
      - file: 03_tools.ipynb
        name: "Tools, Hooks, MCP, Subagents, Skills (features 16-22)"
        order: 40
      - file: 04_automation_headless_ci.ipynb
        name: "Automation, Headless & CI (features 23-27)"
        order: 50
      - file: 05_checklist_capstone.ipynb
        name: "Capstone — 27 Features, 1 Project"
        order: 60
      - file: 09_claude_cicd_pipeline.ipynb
        name: "CI/CD with claude -p — the whole pipeline"
        description: "claude -p as a CI step: review gates, automated fix, mutation testing, and the evidence trail behind a merge."
        order: 70
      - file: 10_claude_add_new_phone_column.ipynb
        name: "End-to-End QA — ticket to signed-off merge"
        description: "Two seats, DEV and QA, take a real ticket through migration, RED to GREEN, security review and PR - neither grading its own work."
        order: 80
      - file: 11_claude_qa_pipeline_exercises.ipynb
        name: "QA Pipeline Exercises — break it on purpose"
        order: 90
"""


def main():
    man = json.loads((ROOT / "manifest.json").read_text())
    files = {p.stem: p.name for p in ROOT.glob("[0-9][0-9]_*.ipynb")}
    out = [HEAD]
    for d, (name, weight) in DOMAINS.items():
        slug = re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")
        out.append(f"  - dir: d{d}_{slug}\n")
        out.append(f'    name: "{name} ({weight}%)"\n')
        out.append(f"    num: {d}\n    order: {d * 10}\n    modules:\n")
        rows = [m for m in man if int(m["skill"].split(".")[0]) == d]
        for i, m in enumerate(rows, 1):
            # manifest titles read "Headline: keyword, keyword" — the app prints the
            # skill number itself, so keep the headline and drop the keyword tail.
            out.append(f'      - file: {files[m["file"]]}\n')
            out.append(f'        name: "{m["title"].split(":")[0].strip()}"\n')
            out.append(f"        order: {i * 10}\n")
        out.append("\n")
    if (ROOT / "workshop").is_dir():
        out.append(WORKSHOP)
    (ROOT / "learning_path.yaml").write_text("".join(out))
    extra = len(sorted((ROOT / "workshop").glob("*.ipynb"))) if (ROOT / "workshop").is_dir() else 0
    print(f"learning_path.yaml — {len(DOMAINS)} domains + setup, "
          f"{len(man) + 1} lessons + {extra} workshop labs")


if __name__ == "__main__":
    main()
